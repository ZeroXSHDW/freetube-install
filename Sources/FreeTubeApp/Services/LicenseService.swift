import Foundation
import CryptoKit

/// License key handling for FreeTubeInstaller Pro.
///
/// Keys are issued by the Cloudflare Worker (`worker/index.js`) after a
/// successful Stripe payment, and have the form:
///
///     FT1.<payloadBase64url>.<signatureBase64url>
///
/// `payload` is `email|product|expiry|issuedAt` (expiry in unix seconds, 0 = lifetime)
/// and `signature` is an Ed25519 signature of the payload bytes. Verification is
/// fully offline — only the public key below is needed, so no phone-home is required.
@MainActor
final class LicenseService: ObservableObject {
    static let shared = LicenseService()

    /// Ed25519 public key (raw 32 bytes, base64). Generated by
    /// `scripts/gen-license-keypair.swift`; replace with your own for production.
    private static let publicKeyBase64 = "HpWSKeCr4vaEeveXy5sZ8SgdOIGnvzgcsYhw9UL7qmE="

    struct LicenseInfo {
        let email: String
        let product: String
        let expiry: Int64      // 0 = lifetime
        let issuedAt: Int64
    }

    @Published var licenseKey: String {
        didSet { UserDefaults.standard.set(licenseKey, forKey: "license.key") }
    }
    @Published var isPro = false
    @Published var licenseInfo: LicenseInfo?

    private init() {
        licenseKey = UserDefaults.standard.string(forKey: "license.key") ?? ""
        if !licenseKey.isEmpty { isPro = Self.verify(licenseKey) }
        if isPro { licenseInfo = Self.parsePayload(from: licenseKey) }
    }

    /// Validates and activates a license key. Returns true on success.
    @discardableResult
    func activate(_ key: String) -> Bool {
        let trimmed = key.trimmingCharacters(in: .whitespacesAndNewlines)
        guard Self.verify(trimmed) else {
            isPro = false
            licenseInfo = nil
            return false
        }
        licenseKey = trimmed
        licenseInfo = Self.parsePayload(from: trimmed)
        isPro = true
        return true
    }

    func deactivate() {
        licenseKey = ""
        licenseInfo = nil
        isPro = false
    }

    var statusText: String {
        guard isPro, let info = licenseInfo else { return "Free (unlicensed)" }
        let licensedTo = info.email.isEmpty ? "unknown" : info.email
        if info.expiry == 0 {
            return "Pro — lifetime license for \(licensedTo)"
        }
        let date = Date(timeIntervalSince1970: TimeInterval(info.expiry))
        return "Pro — licensed to \(licensedTo) until \(DateFormatter.localizedString(from: date, dateStyle: .medium, timeStyle: .none))"
    }

    // MARK: - Verification (offline)

    static func verify(_ key: String) -> Bool {
        let parts = key.split(separator: ".").map(String.init)
        guard parts.count == 3, parts[0] == "FT1",
              let payloadData = Data(base64URLEncoded: parts[1]),
              let signature = Data(base64URLEncoded: parts[2]),
              let pubData = Data(base64Encoded: publicKeyBase64),
              let publicKey = try? Curve25519.Signing.PublicKey(rawRepresentation: pubData) else {
            return false
        }
        guard publicKey.isValidSignature(signature, for: payloadData) else { return false }
        return parsePayloadData(payloadData) != nil
    }

    static func parsePayload(from key: String) -> LicenseInfo? {
        let parts = key.split(separator: ".").map(String.init)
        guard parts.count == 3, let data = Data(base64URLEncoded: parts[1]) else { return nil }
        return parsePayloadData(data)
    }

    private static func parsePayloadData(_ data: Data) -> LicenseInfo? {
        guard let payload = String(data: data, encoding: .utf8) else { return nil }
        let fields = payload.split(separator: "|", omittingEmptySubsequences: false).map(String.init)
        guard fields.count >= 4 else { return nil }
        let expiry = Int64(fields[2]) ?? 0
        let issuedAt = Int64(fields[3]) ?? 0
        if expiry != 0 && expiry < Int64(Date().timeIntervalSince1970) { return nil }
        return LicenseInfo(email: fields[0], product: fields[1], expiry: expiry, issuedAt: issuedAt)
    }
}

private extension Data {
    /// Decodes a base64url string (RFC 4648 §5).
    init?(base64URLEncoded string: String) {
        var s = string
            .replacingOccurrences(of: "-", with: "+")
            .replacingOccurrences(of: "_", with: "/")
        while s.count % 4 != 0 { s.append("=") }
        self.init(base64Encoded: s)
    }
}
